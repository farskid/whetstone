#!/usr/bin/env python3
"""Regenerate src/problems/index.ts from the problem folders.
Order: the Easy warm-ups listed in WARMUPS first, then catalog order (theme letter, then number)."""
import os, re
ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'problems')
WARMUPS = ['f1-debounce', 'a9-promise-all-settled']
dirs = [d for d in os.listdir(ROOT) if os.path.isfile(os.path.join(ROOT, d, 'meta.ts'))]
def key(d):
    m = re.match(r'([a-z])(\d+)-', d)
    return (0, WARMUPS.index(d), '', 0) if d in WARMUPS else (1, 0, m.group(1), int(m.group(2)))
dirs.sort(key=key)
var = lambda d: re.sub(r'\W', '_', d.split('-')[0])
lines = ["import type { Problem } from './types';"]
for d in dirs:
    lines.append(f"import {{ meta as {var(d)}Meta }} from './{d}/meta';")
    lines.append(f"import {{ tests as {var(d)}Tests }} from './{d}/tests';")
lines += ["", "/** Every problem in display order: Easy warm-ups first, then catalog order. Generated by scripts/gen-index.py. */", "export const problems: Problem[] = ["]
lines += [f"  {{ ...{var(d)}Meta, tests: {var(d)}Tests }}," for d in dirs]
lines += ["];", "", "export const problemsById = new Map(problems.map((p) => [p.id, p]));", ""]
open(os.path.join(ROOT, 'index.ts'), 'w').write('\n'.join(lines))
print(f'{len(dirs)} problems:', ' '.join(dirs))

# README table between the problems markers.
readme = os.path.join(ROOT, '..', '..', 'README.md')
def field(d, name):
    m = re.search(name + r": '((?:[^'\\]|\\.)*)'", open(os.path.join(ROOT, d, 'meta.ts')).read())
    return m.group(1).replace("\\'", "'") if m else ''
def count_tests(d):
    return len(re.findall(r'^\s*title:', open(os.path.join(ROOT, d, 'tests.ts')).read(), re.M))
def tags(d):
    return ', '.join(n.replace("\\'", "'") for n in re.findall(r"name: '((?:[^'\\]|\\.)*)'", open(os.path.join(ROOT, d, 'meta.ts')).read()))
rows = ['| id | title | theme | difficulty | tests | tags |', '|---|---|---|---|---|---|']
rows += [f"| {field(d, 'catalogId')} | {field(d, 'title')} | {field(d, 'theme')} | {field(d, 'difficulty')} | {count_tests(d)} | {tags(d)} |" for d in dirs]
text = open(readme).read()
a, b = '<!-- problems:start -->', '<!-- problems:end -->'
if a in text and b in text:
    text = text[:text.index(a) + len(a)] + '\n' + '\n'.join(rows) + '\n' + text[text.index(b):]
    open(readme, 'w').write(text)
